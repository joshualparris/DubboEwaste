FONT = "Helvetica"
FONT_BOLD = "Helvetica-Bold"
FONT_MONO = "Courier"


def register_fonts():
    global FONT, FONT_BOLD, FONT_MONO
    candidates = [
        (
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
        ),
        (
            "/usr/share/fonts/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf",
            "/usr/share/fonts/dejavu/DejaVuSansMono.ttf",
        ),
    ]
    for regular, bold, mono in candidates:
        if all(Path(p).exists() for p in (regular, bold, mono)):
            pdfmetrics.registerFont(TTFont("PackSans", regular))
            pdfmetrics.registerFont(TTFont("PackSansBold", bold))
            pdfmetrics.registerFont(TTFont("PackMono", mono))
            FONT, FONT_BOLD, FONT_MONO = "PackSans", "PackSansBold", "PackMono"
            break


def slug(value: str, limit: int = 105) -> str:
    value = value.replace("&", " and ")
    value = re.sub(r"[^A-Za-z0-9]+", "-", value).strip("-")
    value = re.sub(r"-+", "-", value)
    return (value[:limit].rstrip("-") or "document")


def clean_controls(value: str) -> str:
    value = value.replace("\x00", "")
    return "".join(ch for ch in value if ch in "\n\t" or ord(ch) >= 32)


def inline_text(value: str) -> str:
    value = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", r"Image: \1 (\2)", value)
    value = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", value)
    value = value.replace("**", "").replace("__", "").replace("~~", "").replace(chr(96), "")
    return value.strip()


def esc(value: str) -> str:
    return html.escape(clean_controls(value), quote=False)


class Doc(BaseDocTemplate):
    def __init__(self, filename: str, title: str, footer: str):
        self.footer_text = footer
        super().__init__(
            filename,
            pagesize=A4,
            leftMargin=17 * mm,
            rightMargin=17 * mm,
            topMargin=18 * mm,
            bottomMargin=18 * mm,
            title=title,
            author="Dubbo eWaste / AssetFlow",
            subject="NotebookLM research pack",
            creator="DubboEwaste corrected NotebookLM exporter",
            pageCompression=1,
        )
        frame = Frame(self.leftMargin, self.bottomMargin, self.width, self.height, id="main")
        self.addPageTemplates(PageTemplate(id="main", frames=[frame], onPage=self._footer))

    def _footer(self, canvas, doc):
        canvas.saveState()
        canvas.setFont(FONT, 7)
        canvas.setFillColor(colors.HexColor("#666666"))
        canvas.drawString(self.leftMargin, 8 * mm, f"Dubbo eWaste NotebookLM Pack | {self.footer_text[:105]} | page {doc.page}")
        canvas.restoreState()


