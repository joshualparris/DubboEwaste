"""Build the corrected Dubbo eWaste NotebookLM pack.

Exactly 100 PDFs:
  001: master index generated by this script
  002-045: full selected DubboEwaste repository documents converted to PDF
  046-100: genuine original PDF files downloaded from their publishers

External documents are stored byte-for-byte as downloaded. They are NOT replaced
with summaries or rewritten one-page briefs.
"""

